const LocaleContext = createContext(null);

export function LocaleProvider({ children }) {
  const [locale, setLocale] = useState(() => {
    const fromUrl = new URLSearchParams(window.location.search).get("lang");
    if (DICT[fromUrl]) return fromUrl;
    const saved = localStorage.getItem("fmt_locale");
    return DICT[saved] ? saved : "fr";
  });

  useEffect(() => {
    localStorage.setItem("fmt_locale", locale);
    document.documentElement.lang = locale;
    document.documentElement.dir = DICT[locale]._dir;
  }, [locale]);

  const value = useMemo(() => {
    const table = DICT[locale];
    return {
      locale,
      setLocale,
      dir: table._dir,
      isRTL: table._dir === "rtl",
      t: (key) => table[key] ?? DICT.fr[key] ?? key,
    };
  }, [locale]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  const ctx = useContext(LocaleContext);
  if (!ctx) throw new Error("useLocale must be used inside LocaleProvider");
  return ctx;
}
